// Endpoints
// 1. GET /api/products
app.get('/api/products', (req, res) => {
  // Support both direct array and wrapped response formats
  if (req.query.format === 'object' || req.query.wrapper === 'true') {
    return res.json({
      success: true,
      total: products.length,
      data: products,
    });
  }
  res.json(products);
});

// 2. GET /api/products/:id
app.get('/api/products/:id', (req, res) => {
  const { id } = req.params;
  const product = products.find((p) => p.id === id || p.slug === id);
  if (!product) {
    return res.status(404).json({ success: false, message: 'Product not found' });
  }
  res.json(product);
});

// 3. Health & Status Route
app.get('/', (req, res) => {
  res.json({
    status: 'online',
    service: 'Crafty Kids Co. Mock API',
    port: PORT,
    endpoints: {
      getAllProducts: '/api/products',
      getProductById: '/api/products/:id',
    },
  });
});

app.listen(PORT, HOST, () => {
  console.log(`Crafty Kids Co. Mock API Server running on http://${HOST}:${PORT}`);
});
