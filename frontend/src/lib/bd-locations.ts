export function getDistrictOptions(): Array<{ id: string; label: string; nameEn: string; nameBn: string }> {
  return BD_LOCATIONS.map((loc) => ({
    id: loc.id,
    label: `${loc.nameEn} (${loc.nameBn})`,
    nameEn: loc.nameEn,
    nameBn: loc.nameBn,
  })).sort((a, b) => a.nameEn.localeCompare(b.nameEn));
}

export function getThanasByDistrict(districtNameOrId: string): Array<{ nameEn: string; nameBn: string; label: string }> {
  if (!districtNameOrId) return [];

  const clean = districtNameOrId.trim().toLowerCase();
  const found = BD_LOCATIONS.find(
    (loc) =>
      loc.id === clean ||
      loc.nameEn.toLowerCase() === clean ||
      loc.nameBn.toLowerCase() === clean ||
      clean.includes(loc.nameEn.toLowerCase()) ||
      clean.includes(loc.nameBn.toLowerCase())
  );

  if (!found) return [];

  return found.thanas.map((th) => ({
    nameEn: th.nameEn,
    nameBn: th.nameBn,
    label: `${th.nameBn} (${th.nameEn})`,
  })).sort((a, b) => a.nameEn.localeCompare(b.nameEn));
}
